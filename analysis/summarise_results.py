"""Write results/SUMMARY.md: every headline number, read from the results files.

Nothing in the summary is typed by hand, so the table cannot drift from the results.
A result that has not been produced yet is reported as "not run".

Usage:  python analysis/summarise_results.py
Needs:  results/*.json
Writes: results/SUMMARY.md
"""
import json
from pathlib import Path

import numpy as np

R = Path('results')


def load(name):
    p = R / name
    return json.load(open(p)) if p.exists() else None


def pval(p, perms):
    """A permutation test cannot report a p-value below one over the number of permutations."""
    return f'< {1 / perms:.3f}' if p == 0 else f'{p:.3f}'


def pct(x, digits=1):
    return f'{100 * x:.{digits}f}%'


def main():
    lines = ['# Results summary', '',
             'Generated by `analysis/summarise_results.py` from the JSON files in this folder.',
             'Data: JUMP Cell Painting, cpg0016, CC0. Untreated means DMSO wells.', '']

    e1 = load('e1.json')
    if e1:
        a, b = e1['all_sources'], e1['without_1536_well_sources']
        cm = np.array(a['confusion_matrix']['rows_true_cols_pred'])
        lines += ['## e1: control wells name the lab', '',
                  '| | |', '|---|---|',
                  f"| wells, plates, labs | {a['n_wells']:,}, {a['n_plates']:,}, {a['n_labs']} |",
                  f"| features | {a['n_features']:,} |",
                  f"| balanced accuracy, plates held out | {pct(a['balanced_accuracy'], 2)} |",
                  f"| chance | {pct(a['chance'])} |",
                  f"| wells named wrongly | {int(cm.sum() - np.trace(cm))} |",
                  f"| without the 1536-well labs ({b['n_labs']} labs) | {pct(b['balanced_accuracy'], 2)} |", '']

    rt = load('e1-redteam.json')
    lines += ['## e1 red team', '']
    if rt:
        lines += [f"At most {rt['settings']['wells_per_plate']} wells per plate. Each row changes one thing about the baseline.", '',
                  '| test | balanced accuracy | chance | wells | features |', '|---|---|---|---|---|']
        for name, r in rt['tests'].items():
            lines.append(f"| {name} | {pct(r['balanced_accuracy'], 2)} | {pct(r['chance'])} | {r['n_wells']:,} | {r['n_features']:,} |")
        one = rt['single_features']['one_feature_classifier']
        lines += ['', 'Best single features, one at a time: ' + '; '.join(f'`{k}` {pct(v)}' for k, v in one.items()) + '.', '']
    else:
        lines += ['not run', '']

    vote = load('e1-vote-1053600681.json'); pos = load('e2-plate-position-1053600681.json')
    if vote and pos:
        t = vote['target']
        others = {k: v for k, v in pos['distance_to_each_lab'].items() if k != pos['lab']}
        lines += ['## e2: plate 1053600681', '', '| | |', '|---|---|',
                  f"| wells named as its own lab | {t['wells_named_own_lab']} of {t['n_wells']} |",
                  f"| distance to its own lab's centre | {pos['distance_to_own_lab']} within-plate spreads |",
                  f"| percentile of that among the lab's {pos['own_lab_plates']} plates | {pos['percentile_among_own_lab_plates']} |",
                  f"| distance to the other labs' centres | {min(others.values())} to {max(others.values())} |",
                  f"| plates anywhere nearer another lab's centre than their own | {pos['displaced_plates']['n']} of {pos['n_plates']:,} |", '']

    dr = load('e1b-drift-source_2.json')
    if dr:
        lines += ['## e1b: distance between two plates of one lab, by time apart', '',
                  f"{dr['lab']}, {dr['n_plates']} plates, {dr['n_batches']} batches, {dr['first_batch']} to {dr['last_batch']}.", '',
                  '| time between batches | pairs | median distance | ratio to same batch |', '|---|---|---|---|']
        lines += [f"| {b['gap']} | {b['n_pairs']:,} | {b['median']} | {b['ratio_to_same_batch']} |" for b in dr['bins']]
        lines.append('')

    cc = load('cell-count-1053600681.json')
    if cc:
        lines += ['## Cell count: plate 1053600681', '',
                  f"{cc['cells_per_well']} cells per untreated well. Percentile {cc['same_batch']['percentile']} of "
                  f"{cc['same_batch']['n_plates']} plates in its batch, {cc['whole_lab']['percentile']} of "
                  f"{cc['whole_lab']['n_plates']} in its lab.", '']

    e8 = load('e8-redteam.json')
    if e8:
        c = e8['all_features']; p = c['pooled_within_lab_and_compound']
        lines += ['## e8: same drug, different answer', '',
                  f"{e8['n_plates']} plates, {e8['n_labs']} labs, {e8['n_wells']:,} wells. Each plate is compared with every lab but its own.", '',
                  '| compound | agreement with own lab | with other labs | inside labs: Spearman (p) | between labs: Spearman (p) | effect size, CV of lab means | CV inside a lab |',
                  '|---|---|---|---|---|---|---|']
        for name, v in c['compounds'].items():
            lines.append(f"| {name} | {v['agreement_with_own_lab']} | {v['agreement_with_other_labs']} | "
                         f"{v['within_labs']['spearman']} ({pval(v['within_labs']['p_permutation'], e8['settings']['perms'])}) | "
                         f"{v['between_labs']['spearman']} ({v['between_labs']['p']:.2f}) | "
                         f"{v['effect_size']['cv_of_lab_means_pct']}% | {v['effect_size']['median_cv_within_lab_pct']}% |")
        lines += ['', f"Pooled inside lab and compound: Spearman {p['spearman']}, shuffled {p['null_mean']} "
                      f"(95th percentile {p['null_95pct']}), permutation p {pval(p['p_permutation'], e8['settings']['perms'])}.", '']

    lab_name = lambda s: 'lab ' + s.split('_')[1]
    rp = load('e9-replay.json')
    if rp:
        n = sum(v['n_batches'] for v in rp['labs'].values()); out = sum(v['batches_outside'] for v in rp['labs'].values())
        lines += ['## e9: the certificate, replayed', '',
                  f"Rule: {rp['rule']}. Each lab is scaled on every other lab; z-scores clipped to +-{rp['z_clip']:.0f}.",
                  f"{out} of {n} batches are outside, in {sum(v['batches_outside'] > 0 for v in rp['labs'].values())} of {len(rp['labs'])} labs.", '',
                  '| lab | batches | plates | verdicts in run order (. in distribution, O outside) |', '|---|---|---|---|']
        lines += [f"| {lab_name(k)} | {v['n_batches']} | {v['n_plates']} | `{''.join('O' if b['verdict'] == 'outside' else '.' for b in v['batches'])}` |"
                  for k, v in sorted(rp['labs'].items(), key=lambda kv: int(kv[0].split('_')[1]))]
        lines.append('')
        for lab in [k for k, v in rp['labs'].items() if v['batches_outside']]:
            lines += [f'### {lab_name(lab)}', '',
                      '| run | date | batch | plates | cells per well | vs own history | from baseline | to nearest other | nearest | plates outside | verdict | drift percentile |',
                      '|---|---|---|---|---|---|---|---|---|---|---|---|']
            lines += [f"| {b['run']} | {b['date'] or ''} | {b['batch']} | {b['n_plates']} | {b['cells_per_well']:.0f} | {b['cell_count_vs_own_history'] or ''} | "
                      f"{b['from_baseline']} | {b['to_nearest_other']} | {lab_name(b['nearest_other'])} | {b['plates_outside']} | {b['verdict']} | {b['drift_percentile_in_field']} |"
                      for b in rp['labs'][lab]['batches']]
            lines.append('')
    rr = load('e9-replay-redteam.json')
    if rr:
        lines += ['## e9 red team', '', '| lab | variant | verdicts | features |', '|---|---|---|---|']
        lines += [f"| {lab_name(lab)} | {name} | `{v['verdicts']}` | {v['n_features']:,} |" for lab, vs in rr.items() for name, v in vs.items()]
        lines.append('')

    for name, title in (('e6-what-moved-source_2-first-flag.json', 'first flagged batch'), ('e6-what-moved-source_2.json', 'last batch')):
        e6 = load(name)
        if e6:
            s = e6['share_of_displacement']
            lines += [f"## e6: what moved, {lab_name(e6['lab'])}, {title} ({e6['date']}, {e6['n_plates']} plates)", '',
                      f"{e6['distance_in_spreads']} spreads from the lab's first batch. Cell-level features carry {pct(s['by_level']['cell'])} of the "
                      f"squared displacement and are {pct(e6['share_of_features']['cell'])} of the features. Shifts in standard deviations of the field.", '',
                      '| channel | measurement | features | mean shift | mean absolute shift | share with the same sign |', '|---|---|---|---|---|---|']
            lines += [f"| {g['channel']} | {g['measurement']} | {g['n_features']} | {g['mean_shift']:+.2f} | {g['mean_abs_shift']:.2f} | {pct(g['share_same_sign'])} |"
                      for g in e6['groups'][:12]]
            lines.append('')

    e10 = load('e10-certificate-predicts-answer.json')
    if e10:
        row = lambda name, v: (f"| {name} | " + ' | '.join(
            f"{v[k]['spearman']:+.2f} ({v[k]['n_batches']})" if k in v else '' for k in
            ('drift_vs_agreement_with_own_baseline', 'drift_vs_agreement_with_field')) + ' |')
        a = e10['inside_labs']['drift_vs_agreement_with_own_baseline']
        lines += ['## e10: does the certificate predict the drug answer?', '',
                  f"{e10['n_plates']:,} plates, {e10['n_labs']} labs, {e10['n_wells']:,} wells. Compounds pooled: {', '.join(e10['compounds_pooled'])}.",
                  f"Spearman between a batch's drift from its lab's baseline and the agreement of its drug effects, after removing each lab's mean. "
                  f"Null: batches shuffled inside their lab, {e10['permutations']:,} times; for every row below the permutation p is "
                  f"{pval(0, e10['permutations'])} unless stated.", '',
                  '| batches used | with the lab\'s own first batch (n) | with the field (n) |', '|---|---|---|',
                  row('every batch', e10['inside_labs'])]
        lines += [row(k, v) for k, v in e10['sensitivity'].items()]
        lines += ['', f"Shuffled: {a['null_mean']:+.2f}, 5th percentile {a['null_5pct']:+.2f}.", '',
                  '| lab | flagged batches | agreement with own first batch, flagged | unflagged | exact p, one-sided | arrangements |', '|---|---|---|---|---|---|']
        for lab, v in e10['flagged_against_unflagged'].items():
            o = v['with_own_baseline']
            if o:
                lines.append(f"| {lab_name(lab)} | {o['n_flagged']} | {o['flagged']} | {o['unflagged']} | {o['p_exact_one_sided']:.4f} | {o['n_arrangements']} |")
        lines.append('')

    e11 = load('e11-known-answer.json')
    if e11:
        lines += ['## e11: did the known answer come out?', '', f"Rule: {e11['rule']}.",
                  f"{len(e11['failed'])} batches failed, {sum(f['n_plates'] for f in e11['failed'])} plates.", '',
                  '| lab | batch | plates | agreement with the field | effect size | lab median effect size |', '|---|---|---|---|---|---|']
        lines += [f"| {lab_name(f['lab'])} | {f['batch']} | {f['n_plates']} | {f['agreement']} | {f['size']} | {f['lab_median_size']} |" for f in e11['failed']]
        lines += ['', 'Whole plates, every well compared with the field\'s effect of ' + e11['probe'][0]['compound'] + ':', '',
                  '| batch | verdict | plate | wells the map says hold it | their agreement with the field | wells anywhere that look like it | what the map says those hold |',
                  '|---|---|---|---|---|---|---|']
        lines += [f"| {p['batch']} | {p['batch_verdict']} | {p['plate']} | {', '.join(p['wells_the_map_says_hold_it'])} | "
                  f"{', '.join(str(v) for v in p['their_agreement_with_the_field'])} | {', '.join(p['wells_that_look_like_it']) or 'none'} | "
                  f"{', '.join(p['what_the_map_says_those_hold']) or ''} |" for p in e11['probe']]
        lines.append('')

    e12 = load('e12-field-normalization.json')
    if e12:
        E = e12['every_batch']
        names = {'raw': 'as measured', 'own': 'own controls, by feature', 'scaled': 'own controls, by component', 'field': "the field's frame"}
        ways = [m for m in names if m in E['agree_field']]
        lines += ["## e12: does the field's frame make labs comparable?", '',
                  f"{e12['n_plates']:,} plates, {e12['n_labs']} labs, {E['n_batches']} batches; {e12['batches_left_out_for_failed_positive_controls']} batches left out "
                  f"for failed positive controls. {e12['k']} principal components, shrinkage {e12['shrink']}. Compounds: {', '.join(e12['compounds'])}.", '',
                  '| measure | ' + ' | '.join(names[m] for m in ways) + " | batches where the field's frame is higher |", '|---|' + '---|' * (len(ways) + 1)]
        for key, title in (('agree_field', 'agreement with every other lab'), ('margin', 'margin over the wrong compound'),
                           ('matched', 'right compound recognised'), ('agree_own', "agreement with the lab's own first batch")):
            lines.append(f"| {title} | " + ' | '.join(f"{E[key][m]:.3f}" for m in ways) + f" | {E[key]['field_better_in']} |")
        cv = E['effect_size_cv_across_batches_within_lab']
        lines += [f"| spread of effect size between batches of a lab | " + ' | '.join(f"{cv[m]:.3f}" for m in ways) + ' | lower is tighter |', '']
        grid = sorted(R.glob('e12-field-normalization-*.json'))
        if grid:
            lines += ['| components | shrinkage | agreement, as measured | in the frame | higher in | margin higher in |', '|---|---|---|---|---|---|']
            for f in [R / 'e12-field-normalization.json'] + grid:
                g = json.loads(f.read_text()); a = g['every_batch']['agree_field']
                lines.append(f"| {g['k']} | {g['shrink']} | {a['raw']:.3f} | {a['field']:.3f} | {a['field_better_in']} | {g['every_batch']['margin']['field_better_in']} |")
            lines.append('')

    e13 = load('e13-baseline-density.json')
    if e13:
        lines += ['## e13: is a denser baseline a tighter one?', '',
                  f"{e13['n_plates']:,} plates, {e13['n_labs']} labs, {e13['n_batches']} batches. Distances in within-plate spreads.", '',
                  '| plates in a lab\'s own baseline | distance between two such baselines of one batch | 10th to 90th percentile | batches large enough |', '|---|---|---|---|']
        lines += [f"| {k} | {v['mean']:.2f} | {v['p10']:.2f} to {v['p90']:.2f} | {v['batches_large_enough']} |" for k, v in e13['own_baseline_by_plates'].items()]
        lines += ['', '| labs in the reference | distance between two references that share no lab | 10th to 90th percentile |', '|---|---|---|']
        lines += [f"| {k} | {v['mean']:.2f} | {v['p10']:.2f} to {v['p90']:.2f} |" for k, v in e13['field_reference_by_labs'].items()]
        m = e13['reference_moves_when_one_lab_leaves']
        lines += ['', f"The reference of all {e13['n_labs']} labs moves {m['mean']:.2f} on average, {m['max']:.2f} at most, when one lab is removed.", '']

    (R / 'SUMMARY.md').write_text('\n'.join(lines))
    print('\n'.join(lines))


if __name__ == '__main__':
    main()
